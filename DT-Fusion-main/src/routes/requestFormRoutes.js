const express = require("express")
const auth = require("../middleware/auth")
const controller = require("../controllers/requestFormController")

const router = express.Router()
router.use(auth)
router.get("/config", controller.config)
router.get("/purchase-planning", controller.listPurchasePlanning)
router.put("/purchase-planning/:mpn", controller.savePurchasePlanning)
router.post("/purchase-request-drafts", controller.createPurchaseRequestDraft)
router.get("/", controller.list)
router.post("/", controller.create)
router.post("/bulk", controller.bulkCreate)
router.get("/:id", controller.get)
router.delete("/:id", controller.deleteForm)
router.patch("/:id/requester", controller.updateRequester)
router.patch("/:id/purchase", controller.updatePurchase)
router.post("/:id/purchase-orders", controller.addPurchaseOrder)
router.patch("/:id/purchase-orders/:entryId", controller.updatePurchaseOrder)
router.post("/:id/eta-commitments", controller.addEtaCommitment)
router.patch("/:id/eta-commitments/:entryId", controller.updateEtaCommitment)
router.post("/:id/inventory-transactions", controller.addInventoryTransaction)
router.patch("/:id/inventory-transactions/:entryId", controller.updateInventoryTransaction)
router.patch("/:id/ped", controller.updatePed)
router.patch("/:id/maintenance", controller.updateMaintenance)
router.post("/:id/status", controller.changeStatus)
router.post("/:id/void", controller.voidForm)
router.use(controller.errorHandler)

module.exports = router
